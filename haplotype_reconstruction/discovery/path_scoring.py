"""Prepared, allocation-reusing forward scores for normalized diploid paths.

Validate observed GLs and construct data-only emissions once per block, not
once per trial panel. Ordered diploid states, unequal founder frequencies,
the independent unrepresented-allele state and likelihood normalization match
path_model. No fastmath, state pruning, frequency tying or model approximation.
"""
import numpy as np
from numba import njit, prange
from . import path_model as reference, path_fitting


@njit(cache=True, parallel=True)
def _emissions(gl, observed):
    n, length = observed.shape
    output = np.empty((n, length, 3, 3))
    for sample in prange(n):
        for site in range(length):
            for a in range(3):
                for b in range(3):
                    output[sample, site, a, b] = (
                        reference._emission(a if a < 2 else -1,
                                            b if b < 2 else -1, gl[sample, site])
                        if observed[sample, site] else 1.)
    return output


def prepare_observations(gl, observed, positions, *, generations=3.,
                         recombination_rate_per_bp=5e-8, wildcard_mass=.01,
                         interval_morgans=None):
    """Prepare normalized GL emissions and genetic redraw rates once per block.

    Positions are in base pairs, recombination_rate_per_bp in Morgans/base pair,
    and generations multiplies the copying hazard. Explicit interval_morgans
    replaces position-derived intervals. Unobserved cells have neutral emission.
    """
    # Existing validation is performed at this block boundary. Search panels
    # are trusted binary candidates generated by the existing selector.
    dummy = np.zeros((1, np.asarray(gl).shape[1]), dtype=np.int64)
    _, gl, observed, _, rates = reference._prepare(
        dummy, gl, positions, observed, generations, recombination_rate_per_bp,
        wildcard_mass, interval_morgans, None)
    return dict(emissions=_emissions(gl, observed), rates=rates,
                wildcard_mass=wildcard_mass, gl=gl, observed=observed,
                positions=np.asarray(positions))


def score_prepared(panel, frequencies, prepared):
    """Score a trusted binary panel against the same prepared block observations.

    The forward recursion is the fitter's (path_fitting lane kernels), without
    its trajectory cache: the same per-sample operations in the same order.
    """
    frequencies = np.asarray(frequencies, dtype=np.float64)
    frequencies = frequencies / frequencies.sum()
    pi = np.r_[(1-prepared['wildcard_mass'])*frequencies,
               prepared['wildcard_mass']]
    values = path_fitting.score_lanes(np.ascontiguousarray(panel, dtype=np.int64), pi, prepared)
    return dict(log_likelihood=float(values.sum()), sample_log_likelihood=values,
                state_prior=pi, redraw_probabilities=prepared['rates'])


def score_panel(panel, gl, positions, observed_mask, *, generations=3.,
                recombination_rate_per_bp=5e-8, wildcard_mass=.01,
                interval_morgans=None, founder_frequencies=None):
    """Reference-compatible boundary for checks; search reuses preparation."""
    panel = np.asarray(panel, dtype=np.int64)
    prepared = prepare_observations(gl, observed_mask, positions,
        generations=generations, recombination_rate_per_bp=recombination_rate_per_bp,
        wildcard_mass=wildcard_mass, interval_morgans=interval_morgans)
    frequencies = np.ones(len(panel)) if founder_frequencies is None else founder_frequencies
    return score_prepared(panel, frequencies, prepared)
