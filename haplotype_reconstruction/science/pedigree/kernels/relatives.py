# the relatives' proxies also take the batch's class-transfer cache (or None) and its first child
for _name in ("_second_degree", "_full_sib", "_proxy_kernel"):
    OVERLOADS[f"relatives.{_name}"] = extend(OVERLOADS[f"relatives.{_name}"],
                                              *((*_READ_TERMS, cache, types.int64) for cache in _CACHE_ARGUMENT))
OVERLOADS["relatives._m1_pairs"] = extend(OVERLOADS["relatives._m1_pairs"],
                                           *((*_READ_TERMS, cache) for cache in _CACHE_ARGUMENT))


OVERLOADS["relatives._proxy_kernel"] = tuple(
    sig[:24] + (_reset, _width) + sig[24:] for sig in OVERLOADS["relatives._proxy_kernel"])
OVERLOADS["relatives._second_degree"] = tuple(
    sig[:25] + (_reset, _width) + sig[25:] for sig in OVERLOADS["relatives._second_degree"])
OVERLOADS["relatives._full_sib"] = tuple(
    sig[:25] + (_reset, _width) + sig[25:] for sig in OVERLOADS["relatives._full_sib"])
OVERLOADS["relatives._m1_pairs"] = tuple(
    sig[:25] + (_reset, _width) + sig[25:] for sig in OVERLOADS["relatives._m1_pairs"])

# Parallel wrappers take the live team size from their Python caller.
for _name in ("_proxy_kernel", "_m1_pairs"):
    key = f"relatives.{_name}"
    OVERLOADS[key] = tuple(signature + (types.int64,) for signature in OVERLOADS[key])
