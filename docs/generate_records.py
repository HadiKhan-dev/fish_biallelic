#!/usr/bin/env python3
"""Generate field contracts from dataclass declarations without importing science."""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "haplotype_reconstruction"
TARGET = ROOT / "docs/reference/records.md"


def text(node):
    try:
        value = ast.literal_eval(node)
    except (ValueError, TypeError):
        return ast.unparse(node)
    return str(value)


def cell(value):
    return " ".join(str(value).split()).replace("|", "&#124;")


def render():
    out = [
        "# Record reference",
        "",
        (
            "Generated by `python docs/generate_records.py` from frozen record declarations. Field "
            "order is declaration order; inherited fields precede subclass fields. A schema value here "
            "is the stored product version, distinct from the export manifest format. `stored=False` "
            "fields are reconstructed views and are never persisted. Reader adapters check expected "
            "derivation and supported schema before decoding arrays. See "
            "[contracts](../developer/contracts.md)."
        ),
        "",
    ]
    paths = sorted((PACKAGE / "contracts").glob("*.py")) + [
        PACKAGE / "simulation/truth.py",
        PACKAGE / "simulation/pedigree.py",
    ]
    for path in paths:
        tree = ast.parse(path.read_text())
        for node in tree.body:
            if not isinstance(node, ast.ClassDef) or not any(
                "dataclass" in ast.unparse(d) for d in node.decorator_list
            ):
                continue
            fields = [n for n in node.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)]
            if not fields:
                continue
            out += [
                f"## {path.stem}.{node.name}",
                "",
                f"Source: [{path.relative_to(ROOT).as_posix()}](../../{path.relative_to(ROOT).as_posix()}).",
                "",
            ]
            if node.bases:
                out += ["Extends " + ", ".join(f"`{ast.unparse(base)}`" for base in node.bases) + ".", ""]
            out += [
                "| Field | Type | Role | Axes | Units | Dtype | Stored | Default/schema |",
                "|---|---|---|---|---|---|---|---|",
            ]
            for field in fields:
                metadata = {}
                default = "required"
                value = field.value
                if isinstance(value, ast.Call):
                    kind = ast.unparse(value.func)
                    kw = {v.arg: v.value for v in value.keywords}
                    if kind == "record_field":
                        if value.args:
                            metadata["role"] = text(value.args[0])
                        metadata.update(
                            {k: text(v) for k, v in kw.items() if k in ("role", "axes", "units", "dtype", "stored")}
                        )
                    if "metadata" in kw and isinstance(kw["metadata"], ast.Dict):
                        metadata.update(
                            {text(k): text(v) for k, v in zip(kw["metadata"].keys, kw["metadata"].values, strict=True)}
                        )
                    if kind == "schema_field":
                        default = text(value.args[0]) if value.args else "1"
                        metadata.update(role="diagnostic", axes="()", units="1", dtype="int")
                    elif "default" in kw:
                        default = ast.unparse(kw["default"])
                    elif "default_factory" in kw:
                        default = ast.unparse(kw["default_factory"]) + "()"
                elif value is not None:
                    default = ast.unparse(value)
                cells = (
                    f"`{field.target.id}`",
                    f"`{cell(ast.unparse(field.annotation))}`",
                    metadata.get("role", "—"),
                    metadata.get("axes", "()"),
                    metadata.get("units", "1"),
                    metadata.get("dtype", "See type"),
                    metadata.get("stored", "True"),
                    f"`{cell(default)}`",
                )
                out.append("| " + " | ".join(cell(v) for v in cells) + " |")
            out.append("")
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        stale = not TARGET.exists() or TARGET.read_text() != content
        if stale:
            sys.stdout.write("Stale docs/reference/records.md\n")
        return int(stale)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    tmp = TARGET.with_suffix(".tmp")
    tmp.write_text(content)
    tmp.replace(TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
