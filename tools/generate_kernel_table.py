"""Generate kernel documentation from caller-supplied stage plans and local declarations."""

from __future__ import annotations

import argparse
import importlib
import json
from pathlib import Path


def generate(roots: tuple[str, ...], destination: Path) -> None:
    """Import the declared plan roots and write their overload table without compiling."""
    from haplotype_reconstruction.core.files import atomic_path
    from haplotype_reconstruction.core.kernels import declarations

    for root in roots:
        importlib.import_module(root)
    rows = [
        "# Declared kernels",
        "",
        "Generated by `tools/generate_kernel_table.py`; declarations remain beside each function.",
        "",
        "Roots: " + ", ".join(f"`{root}`" for root in roots),
        "",
        "| Module | Function | Overloads | Parallel | Thread scope / reduction |",
        "|---|---|---|---|---|",
    ]
    for declaration in declarations():
        dispatcher = declaration.dispatcher
        # Code spans: a signature such as Literal[int](-1) would otherwise render as a Markdown link.
        signatures = "<br>".join("`" + str(signature).replace("|", r"\|") + "`" for signature in declaration.overloads)
        parallel = bool(dispatcher.targetoptions.get("parallel", False))
        scope = " ".join((dispatcher.py_func.__doc__ or "").split()) if parallel else "Serial scalar/array kernel"
        rows.append(
            f"| {declaration.module} | {declaration.function} | {signatures} | {parallel} | {scope.replace('|', '/')} |"
        )
    destination.parent.mkdir(parents=True, exist_ok=True)
    with atomic_path(destination) as temporary:
        temporary.write_text("\n".join(rows) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--roots", nargs="*", default=[])
    parser.add_argument("--plan", help="module:function returning the stage task sequence")
    parser.add_argument("--plan-kwargs", default="{}", help="JSON keyword arguments for the fixture plan")
    parser.add_argument("--output", type=Path, default=Path("docs/developer/kernels.md"))
    args = parser.parse_args()
    roots = tuple(args.roots)
    if args.plan:
        from haplotype_reconstruction.stages.graph import preload_modules

        module, function = args.plan.split(":")
        roots += preload_modules(getattr(importlib.import_module(module), function)(**json.loads(args.plan_kwargs)))
    if not roots:
        parser.error("supply --plan or the caller's --roots")
    generate(tuple(dict.fromkeys(roots)), args.output)


if __name__ == "__main__":
    main()
