"""Generate kernel documentation from caller-supplied stage plans and local declarations."""

from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path

PAGE = Path("docs/developer/kernels.md")
_ROOTS_PREFIX = "Roots: "


def render(roots: tuple[str, ...]) -> str:
    """Import the declared plan roots and return their overload table without compiling."""
    from haplotype_reconstruction.core.kernels import declarations

    for root in roots:
        importlib.import_module(root)
    rows = [
        "# Declared kernels",
        "",
        "Generated by `tools/generate_kernel_table.py`; declarations remain beside each function.",
        "",
        _ROOTS_PREFIX + ", ".join(f"`{root}`" for root in roots),
        "",
        "| Module | Function | Overloads | Parallel | Thread scope / reduction |",
        "|---|---|---|---|---|",
    ]
    for declaration in declarations():
        dispatcher = declaration.dispatcher
        # Code spans: a signature such as Literal[int](-1) would otherwise render as a Markdown link.
        signatures = "<br>".join("`" + str(signature).replace("|", r"\|") + "`" for signature in declaration.overloads)
        parallel = bool(dispatcher.targetoptions.get("parallel", False))
        scope = " ".join((dispatcher.py_func.__doc__ or "").split()) if parallel else "Serial scalar/array kernel"
        rows.append(
            f"| {declaration.module} | {declaration.function} | {signatures} | {parallel} | {scope.replace('|', '/')} |"
        )
    return "\n".join(rows) + "\n"


def page_roots(text: str) -> tuple[str, ...]:
    """The roots a generated page names on its Roots line."""
    line = next(line for line in text.splitlines() if line.startswith(_ROOTS_PREFIX))
    return tuple(item.strip().strip("`") for item in line[len(_ROOTS_PREFIX) :].split(","))


def generate(roots: tuple[str, ...], destination: Path) -> None:
    """Write the overload table of ``roots`` to ``destination`` atomically."""
    from haplotype_reconstruction.core.files import atomic_path

    text = render(roots)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with atomic_path(destination) as temporary:
        temporary.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--roots", nargs="*", default=[])
    parser.add_argument("--plan", help="module:function returning the stage task sequence")
    parser.add_argument("--plan-kwargs", default="{}", help="JSON keyword arguments for the fixture plan")
    parser.add_argument("--page-roots", action="store_true", help="reuse the roots named by the existing output page")
    parser.add_argument("--stdout", action="store_true", help="print the table instead of writing the output page")
    parser.add_argument("--output", type=Path, default=PAGE)
    args = parser.parse_args()
    roots = tuple(args.roots)
    if args.page_roots:
        roots += page_roots(args.output.read_text())
    if args.plan:
        from haplotype_reconstruction.stages.graph import preload_modules

        module, function = args.plan.split(":")
        roots += preload_modules(getattr(importlib.import_module(module), function)(**json.loads(args.plan_kwargs)))
    if not roots:
        parser.error("supply --plan, --page-roots or the caller's --roots")
    roots = tuple(dict.fromkeys(roots))
    if args.stdout:
        sys.stdout.write(render(roots))
    else:
        generate(roots, args.output)


if __name__ == "__main__":
    main()
